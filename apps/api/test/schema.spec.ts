import { PrismaClient } from '@prisma/client';
import { afterAll, beforeAll, beforeEach, describe, expect, it } from 'vitest';

/**
 * Task 1.1 — `Currency` and `User` (FR-01, FR-02, ADR-0015).
 *
 * Every claim below is about a rule the **database** holds, not one a DTO holds. Where a rule
 * deliberately lives in the service instead, that absence is pinned here too, so nobody later
 * reads a green suite as proof that the rule is enforced.
 *
 * `beforeEach` is load-bearing: several tests create a row with the same email to prove a FK and
 * a unique constraint, so without it a leftover row from an earlier test makes a later one pass
 * or fail for the wrong reason.
 */

if (!process.env.DATABASE_URL) {
  throw new Error(
    'DATABASE_URL is unset — `vitest.config.ts` loads it from the repo-root .env; check that loader.',
  );
}

const prisma = new PrismaClient();

const CURRENCY = { code: 'TST', name: 'Test Currency', symbol: 'T', minor_unit: 2 };
const OTHER_CURRENCY = { code: 'TS2', name: 'Other Test Currency', symbol: 'U', minor_unit: 3 };
const EMAIL = 'task-1-1-schema@ripis.test';
const RAW_EMAIL = 'task-1-1-raw@ripis.test';

const newUser = (overrides: Partial<{ primary_currency_id: string; email: string }> = {}) => ({
  name: 'Task 1.1',
  email: EMAIL,
  password_hash: 'not-a-real-hash',
  primary_currency_id: CURRENCY.code,
  ...overrides,
});

describe('Currency and User (Task 1.1)', () => {
  beforeAll(async () => {
    await prisma.currency.upsert({ where: { code: CURRENCY.code }, update: {}, create: CURRENCY });
    await prisma.currency.upsert({
      where: { code: OTHER_CURRENCY.code },
      update: {},
      create: OTHER_CURRENCY,
    });
  });

  beforeEach(async () => {
    await prisma.user.deleteMany({ where: { email: { in: [EMAIL, RAW_EMAIL] } } });
  });

  afterAll(async () => {
    await prisma.user.deleteMany({ where: { email: { in: [EMAIL, RAW_EMAIL] } } });
    await prisma.currency.deleteMany({
      where: { code: { in: [CURRENCY.code, OTHER_CURRENCY.code] } },
    });
    await prisma.$disconnect();
  });

  it('defaults role to user and keeps the primary currency the row was created with', async () => {
    const user = await prisma.user.create({ data: newUser() });

    expect(user.role).toBe('user');
    expect(user.primary_currency_id).toBe(CURRENCY.code);
    expect(user.timezone).toBe('Asia/Jakarta');
  });

  it('refuses a user whose primary currency does not exist — the FK, not a form', async () => {
    const error = await prisma.user
      .create({ data: newUser({ primary_currency_id: 'NOPE' }) })
      .catch((e) => e);

    expect(error.code).toBe('P2003');
    expect(await prisma.user.count({ where: { email: EMAIL } })).toBe(0);
  });

  it('refuses that same row in raw SQL — the constraint is Postgres, not the client', async () => {
    // `@default(uuid())` is generated by Prisma, not by the database, so raw SQL must supply
    // the key itself. `gen_random_uuid()` is core PostgreSQL since 13.
    const insert = prisma.$executeRawUnsafe(
      `INSERT INTO "user" (id, name, email, password_hash, primary_currency_id)
       VALUES (gen_random_uuid(), 'raw insert', '${RAW_EMAIL}', 'x', 'NOPE')`,
    );

    await expect(insert).rejects.toThrow(/violates foreign key constraint|23503/i);
  });

  it('refuses a second user with the same email', async () => {
    await prisma.user.create({ data: newUser() });
    const error = await prisma.user.create({ data: newUser() }).catch((e) => e);

    expect(error.code).toBe('P2002');
  });

  it('does NOT hold ADR-0015 — immutability of primary_currency_id is Task 3.1 only', async () => {
    const created = await prisma.user.create({ data: newUser() });
    const moved = await prisma.user.update({
      where: { id: created.id },
      data: { primary_currency_id: OTHER_CURRENCY.code },
    });

    // The database permits the move. If this test ever fails, someone has added a trigger or a
    // CHECK and ADR-0015's enforcement story has changed — which is an ADR, not a quiet fix.
    expect(moved.primary_currency_id).toBe(OTHER_CURRENCY.code);
  });
});
